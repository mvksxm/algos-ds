# Approach: use doubly linked list in order to store cached items. In case if item is added/updated/accessed it should
# be first removed from the ll and then become a head. With performing such logic on each operation. We are making sure
# that our ll contains 'hot' values at the start and 'cold' values at the end.

# TC -> O(1)
# SC -> n = capacity; O(n)


class Node:
    def __init__(self, val=0, key = -1, prev=None, next=None):
        self.val = val
        self.key = key
        self.prev = prev
        self.next = next


class LRUCache:

    def __init__(self, capacity: int):
        self.max_capacity = capacity
        self.curr_capacity = 0
        self.cache_map = {}
        self.cache_head = None
        self.cache_tip = None

    def _add_head(self, node):
        head = self.cache_head
        if head == node: return
        node.next = head
        head.prev = node
        node.prev = None
        self.cache_head = node

    def _detach_node(self, node):
        prev_node = node.prev
        next_node = node.next

        if prev_node: prev_node.next = next_node
        if next_node: next_node.prev = prev_node

        if node == self.cache_tip and prev_node:
            self.cache_tip = prev_node

        if node == self.cache_head and next_node:
            self.cache_head = next_node

    def _remove_tip(self):
        curr_tip = self.cache_tip
        self.cache_tip = curr_tip.prev
        del self.cache_map[curr_tip.key]

    def get(self, key: int) -> int:
        if key not in self.cache_map: return -1
        searched_node = self.cache_map[key]
        self._detach_node(searched_node)
        self._add_head(searched_node)
        return searched_node.val

    def put(self, key: int, value: int) -> None:

        # For existing node
        if key in self.cache_map:
            existing_node = self.cache_map[key]
            existing_node.val = value
            self._detach_node(existing_node)
            self._add_head(existing_node)
            return

        node = Node(value, key)
        self.cache_map[key] = node

        if self.curr_capacity == 0:
            self.cache_head = node
            self.cache_tip = node
            self.curr_capacity += 1
            return

        if self.curr_capacity < self.max_capacity:
            self._add_head(node)
            self.curr_capacity += 1
            return

        self._add_head(node)
        self._remove_tip()

